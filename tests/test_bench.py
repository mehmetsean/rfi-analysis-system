def test_parse_args_quick_and_out(tmp_path: Path) -> None:
    args = parse_args(["--quick", "--runs", "2", "--out", str(tmp_path / "b.md")])
    assert args.quick is True
    assert args.runs == 2
    assert args.out == tmp_path / "b.md"


