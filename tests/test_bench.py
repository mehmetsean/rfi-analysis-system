from rfikit.evaluate import read_inputs

MEASURED = {
    "full": {
        "sets": {
            "A": {
                "methods": {
                    "naive": {
                        "levels": {
                            "strict": {"precision": 0.5, "recall": 0.25},
                            "overlap": {"precision": 0.75, "recall": None},
                        }
                    }
                }
            }
        }
    }
}


def row(method: str = "naive", name: str = "x", chars: int = 100, hits: int = 3) -> Row:
    return Row(method, name, chars, Timing(0.5, 0.25, 1.0), hits, "A")


def test_summarize_uses_the_median() -> None:
    assert summarize([3.0, 1.0, 2.0]) == Timing(2.0, 1.0, 3.0)
    assert summarize([1.0, 1.0, 10.0]) == Timing(1.0, 1.0, 10.0)
    assert summarize([4.0, 1.0, 3.0, 2.0]) == Timing(2.5, 1.0, 4.0)


def test_summarize_needs_a_run() -> None:
    with pytest.raises(ValueError):
        summarize([])


def test_time_runs_warms_up_once() -> None:
    calls: list[int] = []
    ticks = iter([0.0, 1.0, 1.0, 3.0, 3.0, 6.0])

    def work() -> int:
        calls.append(1)
        return 7

    times, hits = time_runs(work, 3, lambda: next(ticks))
    assert times == [1.0, 2.0, 3.0]
    assert hits == 7
    assert len(calls) == 4


def test_ratio_rejects_zero() -> None:
    assert ratio(2.0, 5.0) == 2.5
    with pytest.raises(ValueError):
        ratio(0.0, 1.0)


def test_adversarial_text_size() -> None:
    text = adversarial_text(1000)
    assert len(text) <= 1000
    assert len(text) > 980
    assert text.startswith("IEEE 1547 and ")


def test_rates_read_measured_numbers() -> None:
    found = rates(MEASURED, "naive", "A")
    assert found == {
        "strict.precision": 0.5,
        "strict.recall": 0.25,
        "overlap.precision": 0.75,
        "overlap.recall": None,
    }


def test_rates_missing_level_is_none() -> None:
    assert rates(MEASURED, "naive", "B")["strict.precision"] is None
    assert rates(MEASURED, "rfikit", "A")["strict.recall"] is None


def test_render_table() -> None:
    text = render([row()], MEASURED, {"machine": "m1"}, 2.5, "cmd")
    assert "generated by benchmarks/bench.py" in text
    assert "cmd" in text
    assert "m1" in text
    assert "measured on synthetic data" in text
    assert "| naive | x | 100 | 0.5000 | 0.2500 | 1.0000 | 200 | 3 |" in text
    assert "0.500 | 0.250 | 0.750 | n/a" in text
    assert "2.50" in text


def test_render_without_rates_says_n_a() -> None:
    plain = Row("naive", "adv", 10, Timing(1.0, 1.0, 1.0), 1, None)
    text = render([plain], MEASURED, {}, 1.0, "cmd")
    assert "| 10 | 1.0000 | 1.0000 | 1.0000 | 10 | 1 | n/a | n/a | n/a | n/a |" in text


