"""Extraction benchmark."""

import argparse
import json
import os
import platform
import statistics
import subprocess
import sys
import tempfile
import time
from collections.abc import Callable, Sequence
from dataclasses import dataclass
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parent.parent
sys.path[:0] = [str(ROOT / "benchmarks"), str(ROOT / "scripts")]

from make_bench_inputs import MIB, UNIT  # noqa: E402
from prototype_baseline import naive_spans, prototype_spans  # noqa: E402

from rfikit.cite import extract  # noqa: E402
from rfikit.evaluate import read_inputs  # noqa: E402
from rfikit.notice import LICENSE_LINE  # noqa: E402
from rfikit.synth.generate import generate  # noqa: E402
from rfikit.synth.params import GenParams  # noqa: E402

Json = dict[str, Any]
METHODS = ("naive", "prototype", "rfikit")
LEVELS = ("strict.precision", "strict.recall", "overlap.precision", "overlap.recall")
SEEDS = (101, 102, 103)
SEED_RFIS = 600
SPEC_BOUND = 3.0
QUICK_BOUND = 3.5
TARGET = ROOT / "docs" / "benchmark.md"
WRITTEN = ROOT / "heldout" / "input" / "rfis.csv"
MEASURED = ROOT / "src" / "rfikit" / "measured.json"
COMMAND = "python benchmarks/bench.py"


@dataclass(frozen=True)
class Timing:
    median: float
    low: float
    high: float


@dataclass(frozen=True)
class Row:
    method: str
    name: str
    chars: int
    timing: Timing
    hits: int
    set_name: str | None


def summarize(times: Sequence[float]) -> Timing:
    if not times:
        raise ValueError("no runs")
    return Timing(statistics.median(times), min(times), max(times))


def time_runs(
    work: Callable[[], int], runs: int, clock: Callable[[], float] = time.perf_counter
) -> tuple[list[float], int]:
    hits = work()
    times: list[float] = []
    for _ in range(runs):
        start = clock()
        hits = work()
        times.append(clock() - start)
    return times, hits


def ratio(small: float, big: float) -> float:
    if small <= 0:
        raise ValueError("time must be positive")
    return big / small


def size_label(size: int) -> str:
    if size >= MIB:
        return f"{size // MIB} MiB"
    return f"{size // 1024} KiB"


def seed_label(seeds: Sequence[int], n: int) -> str:
    return (
        f"seed corpus A, timed on seeds {seeds[0]} to {seeds[-1]}, {n} RFIs "
        "per seed (P and R from seeds 101 to 130)"
    )


def adversarial_text(size: int) -> str:
    return UNIT * (size // len(UNIT))


def rates(doc: Json, method: str, set_name: str) -> dict[str, float | None]:
    found: dict[str, float | None] = {}
    try:
        levels = doc["full"]["sets"][set_name]["methods"][method]["levels"]
    except KeyError:
        levels = {}
    for name in LEVELS:
        level, kind = name.split(".")
        found[name] = levels.get(level, {}).get(kind)
    return found


def cell(value: float | None) -> str:
    return "n/a" if value is None else f"{value:.3f}"


def render(
    rows: Sequence[Row],
    doc: Json,
    machine: dict[str, str],
    bound: float,
    command: str,
    runs: int = 5,
) -> str:
    out = [
        f"<!-- generated by benchmarks/bench.py, command: {command} -->",
        "",
        "# Extraction benchmark",
        "",
        f"Generated by benchmarks/bench.py. Command: `{command}`.",
        "",
        "Timing numbers come from one machine and one run of the command "
        "above. Speed will differ on other machines. Precision and recall are "
        "copied from src/rfikit/measured.json, measured on synthetic data in a "
        "full run: family A on report seeds 101 to 130, and the written set. "
        "The timed speed input uses seeds 101 to 103 only. They are not scored "
        "again here.",
        "",
    ]
    for key, value in machine.items():
        out.append(f"- {key}: {value}")
    out += [
        "",
        "The commit above is the code state the numbers were run on.",
        "",
        f"Timing is the median of {runs} runs after one warm-up, with the "
        "minimum and maximum, using time.perf_counter.",
        "",
        "| method | input | chars | median s | min s | max s | chars/s | hits "
        "| strict P | strict R | overlap P | overlap R |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for r in rows:
        t = r.timing
        found = rates(doc, r.method, r.set_name) if r.set_name else {}
        cells = " | ".join(cell(found.get(name)) for name in LEVELS)
        speed = int(r.chars / t.median)
        out.append(
            f"| {r.method} | {r.name} | {r.chars} | {t.median:.4f} | {t.low:.4f} "
            f"| {t.high:.4f} | {speed} | {r.hits} | {cells} |"
        )
    out += [
        "",
        "P and R columns: measured on synthetic data, copied from "
        "src/rfikit/measured.json. The seed corpus rows show P and R from "
        "family A on report seeds 101 to 130, but their timings come from "
        "seeds 101 to 103 only. Baselines have no key levels, so only strict "
        "and overlap span are shown. n/a means no labels exist for that input.",
    ]
    out += [
        "",
        f"Time ratio for rfikit, 2 MiB over 1 MiB: {bound:.2f} (one run, one machine).",
        "",
        f"The spec asks for a ratio under {SPEC_BOUND:.0f}. "
        "This is one machine and one run.",
        "",
        LICENSE_LINE,
        "",
    ]
    return "\n".join(out)


def check_quick(rows: Sequence[Row], bound: float, limit: float) -> list[str]:
    problems: list[str] = []
    if bound > limit:
        problems.append(f"rfikit ratio {bound:.2f} is above {limit:.1f}")
    for method in METHODS:
        mine = [r for r in rows if r.method == method]
        if not mine or any(r.hits == 0 for r in mine):
            problems.append(f"{method} found no citations")
    return problems


def write_file(out: Path, text: str) -> str:
    if out.is_symlink():
        return f"{out.name} is a symbolic link, pick another path"
    if out.exists() and not out.is_file():
        return f"{out.name} is not a regular file"
    fd, temp = tempfile.mkstemp(dir=out.parent, prefix=".bench-")
    try:
        with os.fdopen(fd, "w", encoding="utf-8", newline="") as handle:
            handle.write(text)
        os.replace(temp, out)
    except OSError as error:
        Path(temp).unlink(missing_ok=True)
        return f"cannot write {out.name}: {error.strerror}"
    return ""


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser()
    parser.add_argument("--quick", action="store_true")
    parser.add_argument("--runs", type=int, default=5)
    parser.add_argument("--out", type=Path, default=None)
    args = parser.parse_args(argv)
    if args.runs < 1:
        parser.error("--runs must be at least 1")
    return args


def method_work(method: str, texts: Sequence[str]) -> Callable[[], int]:
    def naive() -> int:
        return sum(len(naive_spans(t)) for t in texts)

    def prototype() -> int:
        return sum(len(prototype_spans(t)) for t in texts)

    def rfikit() -> int:
        return sum(len(extract(t)) for t in texts)

    return {"naive": naive, "prototype": prototype, "rfikit": rfikit}[method]


def seed_texts(seeds: Sequence[int], n: int) -> list[str]:
    texts: list[str] = []
    for seed in seeds:
        for made in generate(seed, n, GenParams(families=("A",))).rfis:
            r = made.rfi
            texts += [r.subject, r.question, r.response]
    return texts


def written_texts() -> list[str]:
    texts: list[str] = []
    for r in read_inputs(WRITTEN):
        texts += [r.subject, r.question, r.response]
    return texts


def machine_info() -> dict[str, str]:
    return {
        "machine": platform.machine(),
        "OS": platform.platform(),
        "CPU count": str(os.cpu_count()),
        "Python": platform.python_version(),
        "rfikit commit": commit(),
    }


def commit() -> str:
    try:
        sha = subprocess.run(
            ["git", "rev-parse", "--short", "HEAD"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
        dirty = subprocess.run(
            ["git", "status", "--porcelain", "--untracked-files=no"],
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=True,
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return "unknown"
    return sha + (" (uncommitted changes)" if dirty else "")


def measure(
    inputs: Sequence[tuple[str, list[str], str | None]], runs: int
) -> list[Row]:
    rows: list[Row] = []
    for name, texts, set_name in inputs:
        chars = sum(len(t) for t in texts)
        for method in METHODS:
            times, hits = time_runs(method_work(method, texts), runs)
            rows.append(Row(method, name, chars, summarize(times), hits, set_name))
    return rows


def rfikit_ratio(rows: Sequence[Row], small: str, big: str) -> float:
    def find(name: str) -> float:
        return next(
            r.timing.median for r in rows if r.method == "rfikit" and r.name == name
        )

    return ratio(find(small), find(big))


def main(argv: Sequence[str] | None = None) -> int:
    args = parse_args(argv)
    sizes = (MIB // 8, MIB // 4) if args.quick else (MIB, 2 * MIB)
    seeds, n = ((SEEDS[0],), 40) if args.quick else (SEEDS, SEED_RFIS)
    names = [f"adversarial {size_label(s)}" for s in sizes]
    inputs: list[tuple[str, list[str], str | None]] = [
        (
            seed_label(seeds, n),
            seed_texts(seeds, n),
            "A",
        ),
        ("written set", written_texts(), "written"),
    ]
    for name, size in zip(names, sizes, strict=True):
        inputs.append((name, [adversarial_text(size)], None))
    rows = measure(inputs, args.runs)
    doc = json.loads(MEASURED.read_text(encoding="utf-8"))
    bound = rfikit_ratio(rows, names[0], names[1])
    command = COMMAND + (" --quick" if args.quick else "")
    text = render(rows, doc, machine_info(), bound, command, args.runs)
    out = args.out or (None if args.quick else TARGET)
    if out is not None:
        error = write_file(out, text)
        if error:
            print(f"bench: {error}", file=sys.stderr)
            return 1
    if args.quick:
        problems = check_quick(rows, bound, QUICK_BOUND)
        for line in problems:
            print(line, file=sys.stderr)
        print(f"quick run: ratio {bound:.2f}, {len(rows)} rows")
        return 1 if problems else 0
    print(f"ratio {bound:.2f}, wrote {out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
